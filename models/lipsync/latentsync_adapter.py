"""LatentSync adapter (bytedance/LatentSync), versions 1.5 and 1.6.

Audio-conditioned latent diffusion with SyncNet supervision and TREPA
temporal consistency. Slower than MuseTalk, higher fidelity — plan §8 marks
it as the final-render / results-table model.

Weights are Apache-2.0 — commercial-OK, which is why the registry
licence string says `apache-2.0`.

**One codebase, two versions, and switching is two changes not one.**
`docs/changelog_v1.6.md` upstream: "we did not make any changes to the model
structure or training strategy; the only modification was upgrading the
training dataset to 512x512 videos. Therefore, the current code is
compatible with both LatentSync 1.5 and 1.6. To switch between versions, you
only need to load the corresponding checkpoint and modify the `resolution`
parameter in the U-Net config file."

So a version here is a (checkpoint, resolution) PAIR, and `VERSIONS` below
keeps them together. Setting one without the other is the failure this
adapter exists to prevent: the architecture is identical, so a 1.5
checkpoint loads happily under a 512 config and simply generates badly --
no error, no warning, a finished mp4 with a soft mouth. `_ensure_loaded`
therefore reads `data.resolution` out of the config and refuses a pair that
disagrees.

**Why 1.5 is worth having on this host.** Upstream's README gives the
inference minimums: **8 GB for 1.5, 18 GB for 1.6**. These are 16311 MiB
cards (CLAUDE.md §1), so 1.6 at 512 is the one model here with no comfort
margin, while 1.5 at 256 leaves roughly half the card free. The trade is
exactly the thing lip-sync produces: 1.6 exists because "the teeth and lips
generated by LatentSync 1.5 are blurry".

The upstream repo exposes `scripts/inference.py` taking --unet_config_path,
--inference_ckpt_path, --video_path, --audio_path, --video_out_path, etc.
We shell out rather than import — LatentSync pins specific diffusers /
accelerate versions.

Env:
  LATENTSYNC_REPO              (default: models/lipsync/vendor/latentsync,
                                falling back to third_party/LatentSync)
  LATENTSYNC_VERSION           (1.5 | 1.6; default 1.6)
  LATENTSYNC_UNET_CONFIG       (overrides the version's config)
  LATENTSYNC_UNET_CKPT         (overrides the version's checkpoint)
  LATENTSYNC_PYTHON            (default: current python)
"""
from __future__ import annotations

import logging
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Optional

from backend.media_io import probe_video as _probe_video
from .base import (BaseLipSync, LipSyncRequest, LipSyncResult,
                   resolve_env_python, resolve_vendor_repo, run_streaming)

log = logging.getLogger(__name__)


DEFAULT_REPO = "third_party/LatentSync"

#: version -> (unet config, checkpoint, the resolution that config MUST have)
#:
#: The checkpoint and the resolution travel together because upstream says
#: they must. The third element is not redundant: it is what lets
#: `_ensure_loaded` catch a config that has been pointed somewhere else
#: (`LATENTSYNC_UNET_CONFIG`, or a hand-edited yaml) while the checkpoint
#: stayed put.
#:
#: 1.5's checkpoint is NOT the same file as 1.6's. Upstream ships them from
#: different HF repos under the same basename, so they are given distinct
#: names here -- dropping 1.5's weights on top of `latentsync_unet.pt` would
#: silently turn every 1.6 run into a mismatched one.
VERSIONS = {
    "1.5": ("configs/unet/stage2.yaml",
            "checkpoints/latentsync_unet_1.5.pt", 256),
    "1.6": ("configs/unet/stage2_512.yaml",
            "checkpoints/latentsync_unet.pt", 512),
}
DEFAULT_VERSION = "1.6"

#: Where each version's weights come from, for the error message. Naming the
#: file AND the repo matters: both are called `latentsync_unet.pt` upstream.
_HF_REPO = {"1.5": "ByteDance/LatentSync-1.5",
            "1.6": "ByteDance/LatentSync-1.6"}


def _config_resolution(cfg_path: Path) -> Optional[int]:
    """`data.resolution` out of a UNet yaml, or None if unreadable.

    Parsed with a regex rather than yaml so the `dubbing` env does not gain
    a dependency for one integer, and so an upstream config using anchors or
    a syntax we do not expect degrades to "cannot tell" instead of raising.
    """
    import re
    try:
        text = cfg_path.read_text()
    except OSError:
        return None
    m = re.search(r"^\s*resolution:\s*(\d+)", text, re.M)
    return int(m.group(1)) if m else None


class LatentSyncSync(BaseLipSync):
    name = "latentsync"
    licence = "apache-2.0"
    version = DEFAULT_VERSION

    def __init__(
        self,
        device: Optional[str] = None,
        *,
        repo_path: Optional[str] = None,
        version: Optional[str] = None,
        unet_config_path: Optional[str] = None,
        unet_ckpt_path: Optional[str] = None,
        python_bin: Optional[str] = None,
        inference_steps: int = 20,
        guidance_scale: float = 2.0,
        seed: int = 1247,
        enable_deepcache: bool = False,
        memory_efficient: bool = True,
        targets_npz: Optional[str] = None,
        cuda_device: Optional[int] = None,
    ):
        super().__init__(device=device, cuda_device=cuda_device)
        self.repo_path = resolve_vendor_repo(
            "latentsync", "LATENTSYNC_REPO", repo_path, legacy=DEFAULT_REPO)
        # Explicit argument, then env, then the subclass's own version. The
        # subclass is how the registry offers 1.5 as its own choice, so it
        # must lose to someone asking for a version outright.
        ver = str(version or os.getenv("LATENTSYNC_VERSION")
                  or self.version).strip()
        if ver not in VERSIONS:
            raise ValueError(
                f"Unknown LatentSync version {ver!r}. "
                f"Available: {', '.join(sorted(VERSIONS))}")
        self.version = ver
        cfg_default, ckpt_default, self.expected_resolution = VERSIONS[ver]
        self.unet_config_path = unet_config_path or os.getenv("LATENTSYNC_UNET_CONFIG") \
            or cfg_default
        self.unet_ckpt_path = unet_ckpt_path or os.getenv("LATENTSYNC_UNET_CKPT") \
            or ckpt_default
        self.python_bin = resolve_env_python("latentsync", "latentsync", python_bin)
        self.inference_steps = inference_steps
        self.guidance_scale = guidance_scale
        self.seed = seed
        # Upstream wires DeepCache in `scripts/inference.py` but leaves it
        # off: a full UNet pass every `cache_interval` (3) steps, the deep
        # blocks reused in between. It attacks the SAME per-step cost as
        # `inference_steps`, so the two multiply rather than add -- at 10
        # steps it leaves only 4 full passes, which is where the mouth
        # starts to soften. Pair it with 20 steps, not 10, unless the
        # comparison says otherwise.
        self.enable_deepcache = bool(enable_deepcache)
        # Upstream builds the whole composited clip in RAM -- a list of
        # full-resolution frames, then `np.stack` of that list, while the
        # decoded source is still alive. Three copies, ~14 GB on a 750-frame
        # 1080p shard. With this on, the frames are composited straight into
        # the encoder and only the source copy remains (~4.7 GB). The PIXELS
        # ARE IDENTICAL -- it changes when frames are freed, not how they are
        # drawn -- so unlike the speed knobs it costs nothing to leave on.
        self.memory_efficient = bool(memory_efficient)
        # Per-frame face targets. CLAUDE.md records "lip-sync adapters do not
        # choose the SPEAKING face" as a known rough edge, and LatentSync is
        # one of the adapters that ignored `coord_list` rather than pretending
        # to honour it. This is how it stops ignoring it: the targets carry
        # 106 landmarks per frame, which is the ENTIRE contribution the stock
        # InsightFace pass makes, so supplying them reproduces the stock warp
        # while choosing the face.
        #
        # Indexed against the clip THIS adapter is handed, not the whole
        # video -- `backend.lipsync` renumbers frames from zero for every
        # shard and segment, so the caller slices before passing. The
        # pipeline refuses a length mismatch rather than animating the wrong
        # frames.
        self.targets_npz = str(targets_npz) if targets_npz else None

    def _ensure_loaded(self) -> None:
        if self._loaded:
            return
        if not self.repo_path.exists():
            raise RuntimeError(
                f"LatentSync repo not found at {self.repo_path}. "
                f"Clone: git clone https://github.com/bytedance/LatentSync "
                f"{self.repo_path}"
            )
        inference = self.repo_path / "scripts" / "inference.py"
        if not inference.exists():
            raise RuntimeError(f"LatentSync scripts/inference.py missing at {inference}")
        cfg = (self.repo_path / self.unet_config_path) \
              if not Path(self.unet_config_path).is_absolute() \
              else Path(self.unet_config_path)
        ckpt = (self.repo_path / self.unet_ckpt_path) \
               if not Path(self.unet_ckpt_path).is_absolute() \
               else Path(self.unet_ckpt_path)
        if not cfg.exists():
            raise RuntimeError(f"LatentSync UNet config missing: {cfg}")
        if not ckpt.exists():
            raise RuntimeError(
                f"LatentSync {self.version} UNet checkpoint missing: {ckpt}. "
                f"Download it from https://huggingface.co/"
                f"{_HF_REPO.get(self.version, 'ByteDance/LatentSync-1.6')} "
                f"and save it under that exact name -- both versions ship "
                f"the file as `latentsync_unet.pt`, so they are kept apart "
                f"here by filename."
            )

        # The check this adapter exists for. The two versions share an
        # architecture, so a 1.5 checkpoint loads without complaint under a
        # 512 config and simply generates badly: no error, no warning, a
        # finished mp4 with a soft mouth, after ~80x the clip length of GPU
        # time. Upstream is explicit that BOTH have to move together.
        got = _config_resolution(cfg)
        if got is not None and got != self.expected_resolution:
            raise RuntimeError(
                f"LatentSync {self.version} expects a {self.expected_resolution}"
                f"x{self.expected_resolution} UNet config, but {cfg} declares "
                f"resolution: {got}. The checkpoint and the resolution are a "
                f"pair -- a mismatch renders without erroring and only looks "
                f"wrong. Use {VERSIONS[self.version][0]}, or set "
                f"LATENTSYNC_VERSION to the version this config belongs to."
            )
        if got is None:
            log.warning("latentsync: could not read `resolution` from %s; "
                        "proceeding without the version/config check", cfg)
        self._loaded = True

    def sync(self, request: LipSyncRequest) -> LipSyncResult:
        self._ensure_loaded()
        out = Path(request.out_path)
        out.parent.mkdir(parents=True, exist_ok=True)

        cmd = [
            self.python_bin, "-m", "scripts.inference",
            "--unet_config_path", self.unet_config_path,
            "--inference_ckpt_path", self.unet_ckpt_path,
            "--video_path", str(Path(request.video).resolve()),
            "--audio_path", str(Path(request.audio).resolve()),
            "--video_out_path", str(out.resolve()),
            "--inference_steps", str(self.inference_steps),
            "--guidance_scale", str(self.guidance_scale),
            "--seed", str(self.seed),
            "--temp_dir", str((out.parent / f"_temp_gpu{self.cuda_device}").resolve()),
        ]
        if self.enable_deepcache:
            cmd.append("--enable_deepcache")
        if self.memory_efficient:
            cmd.append("--memory_efficient")
        # `request.extra["targets_npz"]` wins over the constructor kwarg: the
        # sharded and segmented paths cut the clip and hand each piece its own
        # slice, so the per-request value is the one indexed against the frames
        # this call will actually see.
        targets = (request.extra or {}).get("targets_npz") or self.targets_npz
        if targets:
            cmd += ["--targets_npz", str(Path(targets).resolve())]
        log.info("latentsync[gpu=%s]: %s", self.cuda_device, " ".join(cmd))
        proc = subprocess.run(cmd, cwd=str(self.repo_path),
                              env=self._subprocess_env(),
                              capture_output=True, text=True)
        if proc.returncode != 0:
            return LipSyncResult(
                model_name=f"latentsync-{self.version}", out_video=out,
                duration_s=0.0, fps=0.0,
                error=f"latentsync rc={proc.returncode}: {proc.stderr.strip()[-3000:]}",
            )
        fps, dur = _probe_video(out)
        return LipSyncResult(
            model_name=f"latentsync-{self.version}", out_video=out,
            duration_s=dur, fps=fps,
            extra={"licence": self.licence,
                   "version": self.version,
                   "resolution": self.expected_resolution,
                   "unet_config": self.unet_config_path,
                   "inference_steps": self.inference_steps,
                   "guidance_scale": self.guidance_scale,
                   "deepcache": self.enable_deepcache,
                   "memory_efficient": self.memory_efficient},
        )

    def sync_many(self, requests):
        """Render many pieces in ONE process, loading the diffusion stack once.

        The vendored `scripts/inference.py` builds the pipeline for a single
        (video, audio) call, so a segmented render used to reload the whole
        stack -- the heaviest load of the three models -- per piece. For more
        than one piece this shells out to `_latentsync_worker.py`, which does
        the one-time setup once and loops the pieces through the same
        `pipeline(...)` call. A single piece keeps the proven per-call path
        unchanged.
        """
        if not requests:
            return []
        if len(requests) == 1:
            return [self.sync(requests[0])]
        self._ensure_loaded()

        import json
        import tempfile

        worker = Path(__file__).resolve().parent / "_latentsync_worker.py"
        manifest = []
        for request in requests:
            out = Path(request.out_path)
            out.parent.mkdir(parents=True, exist_ok=True)
            # The per-request targets win over the constructor kwarg: the
            # caller slices the targets per piece, so the per-request value is
            # the one indexed against the frames this piece will see.
            targets = (request.extra or {}).get("targets_npz") or self.targets_npz
            manifest.append({
                "video": str(Path(request.video).resolve()),
                "audio": str(Path(request.audio).resolve()),
                "out": str(out.resolve()),
                # Own temp dir per piece so sequential pieces cannot stomp each
                # other's intermediates.
                "temp_dir": str((out.parent /
                                 f"_temp_gpu{self.cuda_device}_{out.stem}").resolve()),
                "targets_npz": str(Path(targets).resolve()) if targets else None,
            })

        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as mf:
            json.dump(manifest, mf)
            mf_path = mf.name

        cmd = [
            self.python_bin, str(worker),
            "--repo", str(self.repo_path.resolve()),
            "--manifest", mf_path,
            "--unet_config_path", self.unet_config_path,
            "--inference_ckpt_path", self.unet_ckpt_path,
            "--inference_steps", str(self.inference_steps),
            "--guidance_scale", str(self.guidance_scale),
            "--seed", str(self.seed),
        ]
        if self.enable_deepcache:
            cmd.append("--enable_deepcache")
        if self.memory_efficient:
            cmd.append("--memory_efficient")
        log.info("latentsync[gpu=%s]: warm worker, %d piece(s): %s",
                 self.cuda_device, len(requests), " ".join(cmd))
        try:
            # Stream live: the worker prints `[worker] start/ok/fail` per piece,
            # so progress lands in run.log as each piece runs rather than in one
            # block when the whole batch finishes.
            proc = run_streaming(cmd, cwd=str(self.repo_path),
                                 env=self._subprocess_env(), log=log,
                                 tag=f"latentsync[gpu={self.cuda_device}]")
        finally:
            Path(mf_path).unlink(missing_ok=True)

        # Per-piece failure reasons the worker printed, keyed by output path.
        reasons = {}
        for line in (proc.stdout or "").splitlines():
            if line.startswith("[worker] fail "):
                rest = line[len("[worker] fail "):]
                path, _, why = rest.partition(" :: ")
                reasons[path.strip()] = why.strip() or "worker reported failure"

        # A non-zero exit WITHOUT any per-piece reason is the batch dying at
        # load (bad env, missing checkpoint): attribute it to every piece.
        batch_err = None
        if proc.returncode != 0 and not reasons:
            batch_err = (f"latentsync worker rc={proc.returncode}: "
                         f"{proc.stdout.strip()[-3000:]}")

        results = []
        for request in requests:
            out = Path(request.out_path)
            key = str(out.resolve())
            # The file is the arbiter: upstream can exit 0 having written
            # nothing (CLAUDE.md §1), so a present+non-empty file is success
            # even if a reason was mis-parsed, and a missing file is failure
            # even at rc=0.
            ok = out.is_file() and out.stat().st_size > 0
            if not ok:
                err = (reasons.get(key) or batch_err
                       or f"latentsync produced no output for {out.name}")
                results.append(LipSyncResult(
                    model_name=f"latentsync-{self.version}", out_video=out,
                    duration_s=0.0, fps=0.0, error=err))
                continue
            fps, dur = _probe_video(out)
            results.append(LipSyncResult(
                model_name=f"latentsync-{self.version}", out_video=out,
                duration_s=dur, fps=fps,
                extra={"licence": self.licence, "version": self.version,
                       "resolution": self.expected_resolution,
                       "unet_config": self.unet_config_path,
                       "inference_steps": self.inference_steps,
                       "guidance_scale": self.guidance_scale,
                       "deepcache": self.enable_deepcache,
                       "memory_efficient": self.memory_efficient,
                       "warm_batch": len(requests)}))
        return results



class LatentSync15Sync(LatentSyncSync):
    """LatentSync 1.5 — 256x256, ~8 GB inference.

    A separate REGISTRY entry rather than a kwarg on `latentsync`, because
    a kwarg cannot be reached from the operator UI: the replay path
    (`edit_agent._rerun_lipsync_only`) forwards only `batch_size`, so a
    version passed as an adapter kwarg would be unreachable from the one
    place the model is actually chosen. Same reasoning, and same shape, as
    `wav2lip_hd` subclassing `wav2lip`.

    Everything else is inherited, so 1.5 tracks 1.6's behaviour -- the
    env-python resolution, the config/checkpoint pairing check, the
    `rc=0 but no file` handling -- rather than forking it.
    """
    name = "latentsync15"
    version = "1.5"
